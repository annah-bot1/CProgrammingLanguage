#include<stdio.h>
int main()
{
    int x;
    int y;
    scanf ("%d", &x);
    scanf ("%d", &y);
    printf("sum of the two numbers:%d\n", x+y);
    printf("difference between the two numbers:%d\n", x-y);
    printf("product of the two numbers:%d\n", x*y);
    printf("quotient of the two numbers:%d\n", x/y);
    return 0;
}